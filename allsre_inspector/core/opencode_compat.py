"""Small compatibility layer for OpenCode V1 and V2 HTTP servers.

OpenCode V2 moved the HTTP API below ``/api`` and protects a locally served
instance with a server password.  Inspector deliberately keeps one code path
for both versions during the rollout: existing Workers can still run V1, while
new Workers use V2 without silently proxying an unauthenticated request.
"""
from __future__ import annotations

import re
import subprocess
import base64
from dataclasses import dataclass
from typing import Mapping


def detect_opencode_major(executable: str, configured: object = "auto") -> int:
    """Return the configured/detected major version, conservatively V1 on error."""
    value = str(configured or "auto").strip().lower()
    if value in {"1", "v1"}:
        return 1
    if value in {"2", "v2"}:
        return 2
    try:
        result = subprocess.run(
            [str(executable), "--version"], capture_output=True, text=True,
            timeout=5, check=False,
        )
    except (OSError, subprocess.SubprocessError, TypeError):
        return 1
    match = re.search(r"(?:^|\s)v?(\d+)\.", (result.stdout or "") + "\n" + (result.stderr or ""))
    return int(match.group(1)) if match else 1


@dataclass(frozen=True)
class OpenCodeApi:
    """Map Inspector's stable V1-shaped internal calls to a selected server."""

    major: int = 1
    password: str = ""

    @property
    def v2(self) -> bool:
        return self.major >= 2

    def path(self, method: str, path: str) -> str:
        if not self.v2 or path.startswith("/api/"):
            return path
        # V2 serves the WebUI and its static assets from the root document;
        # these are browser routes, not API resources.  Prefixing them with
        # ``/api`` makes the SPA deep-link return 404.
        if (
            path == "/"
            or path.startswith((
                "/_assets/", "/assets/", "/icons/", "/favicon", "/site.webmanifest",
                "/manifest", "/social-share", "/.well-known/", "/__allsre/",
            ))
        ):
            return path
        method = method.upper()
        if path == "/global/health":
            return "/api/info"
        if path == "/global/event":
            return "/api/event"
        if path == "/session":
            return "/api/session"
        if path.startswith("/session/"):
            suffix = path[len("/session/"):]
            if suffix.endswith("/abort"):
                return "/api/session/" + suffix[:-len("/abort")] + "/interrupt"
            if suffix.endswith("/message") and method == "POST":
                return "/api/session/" + suffix[:-len("/message")] + "/prompt"
            if suffix.endswith("/prompt_async") and method == "POST":
                return "/api/session/" + suffix[:-len("/prompt_async")] + "/prompt"
            return "/api/session/" + suffix
        return "/api" + path

    def payload(self, method: str, path: str, payload: dict | None) -> dict | None:
        """Translate a V1 prompt body into V2's text shape.

        V1 posts ``{"parts": [{"type": "text", "text": ...}]}`` to
        ``/session/{id}/message``; V2 accepts ``{"text": ...}`` on
        ``/api/session/{id}/prompt`` and rejects the V1 body with
        ``InvalidRequestError: Missing key ["text"]``.
        """
        if not self.v2 or not isinstance(payload, dict):
            return payload
        if method.upper() != "POST" or not re.fullmatch(r"/session/[^/]+/(?:message|prompt_async)", path):
            return payload
        parts = payload.get("parts")
        if not isinstance(parts, list):
            return payload
        text = "\n".join(
            str(part.get("text") or "") for part in parts
            if isinstance(part, dict) and part.get("type") == "text"
        )
        result = {key: value for key, value in payload.items() if key != "parts"}
        result["text"] = text
        return result

    def headers(self, headers: Mapping[str, str] | None = None) -> dict[str, str]:
        result = dict(headers or {})
        if self.v2 and self.password:
            # Never accept a browser supplied credential; the Worker-created
            # loopback password is the sole credential for this server.
            for key in tuple(result):
                if key.lower() == "authorization":
                    result.pop(key, None)
            # V2's local server deliberately uses HTTP Basic auth.  The user
            # name is fixed by OpenCode; only the per-child-process password
            # is generated by Inspector.
            encoded = base64.b64encode(f"opencode:{self.password}".encode("utf-8")).decode("ascii")
            result["Authorization"] = f"Basic {encoded}"
        return result
